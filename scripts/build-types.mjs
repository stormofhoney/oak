// Combines the vendored acorn type declarations and the acorn-walk type
// declarations into a single Oak declaration file (dist/oak.d.ts and
// dist/oak.d.mts).
//
// acorn-walk's walk.d.ts starts with `import * as acorn from "acorn"` and
// references acorn.* types throughout. Since Oak bundles both libraries into
// one namespace, we strip that import and drop the `acorn.` prefix so the walk
// declarations reference the acorn types that are emitted above them in the
// same file.

import {readFile, writeFile} from "node:fs/promises"

const acornDts = await readFile("src/acorn/acorn.d.ts", "utf8")
const walkDts = await readFile("src/walk/walk.d.ts", "utf8")
const extrasDts = await readFile("src/extras.d.ts", "utf8")

// Remove the `import * as acorn from "acorn"` line and strip the `acorn.`
// namespace prefix from every type reference.
const walkBody = walkDts
  .replace(/^import\s+\*\s+as\s+acorn\s+from\s+["']acorn["'];?\s*\n/m, "")
  .replace(/\bacorn\./g, "")

const combined = `// Oak — combined type declarations for acorn (parser) + acorn-walk (walker).
// Generated by scripts/build-types.mjs. Do not edit by hand.

${acornDts}

// ---- acorn-walk -----------------------------------------------------------

${walkBody}

// ---- extra utilities ------------------------------------------------------

${extrasDts}
`

await writeFile("dist/oak.d.ts", combined)
await writeFile("dist/oak.d.mts", combined)
console.log("wrote dist/oak.d.ts and dist/oak.d.mts")
